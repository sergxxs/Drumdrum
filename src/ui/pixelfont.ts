/** Packed glyph bitmaps: 7 bytes each, 5 bits used per row. */
const GLYPHS = new Map<string, Uint8Array>();
for (const ch in RAW) {
  const rows = RAW[ch];
  const packed = new Uint8Array(rows.length);
  for (let r = 0; r < rows.length; r++) {
    let bits = 0;
    for (let c = 0; c < GLYPH_W; c++) {
      if (rows[r][c] === '1') bits |= 1 << (GLYPH_W - 1 - c);
    }
    packed[r] = bits;
  }
  GLYPHS.set(ch, packed);
}

const FALLBACK = GLYPHS.get('?')!;

export function glyph(ch: string): Uint8Array {
  return GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get(ch) ?? FALLBACK;
}

/** Width in pixels of a string at a given scale (with 1px letter gap). */
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}
